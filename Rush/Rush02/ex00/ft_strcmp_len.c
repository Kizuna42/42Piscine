#include "declaration.h"

/**
 * @fn
 * ヌル文字で終了する文字列 s1 および s2 を長さを優先して辞書式順序で比較する
 * @param s1 １つ目の比較対象の文字列
 * @param s2 ２つ目の比較対象の文字列
 * @return  まずs1 が s2 より文字列の長さが等しくない場合は長さが大きいか、あるいは
 * 小さいかに応じて、それぞれ0よりも大きい、あるいは0よりも小さい整数を返す。
 * 長さが等しい場合はs1 が s2 よりも大きいか、等しいか、あるいは小さいかに応じ
 * て、 それぞれ 0 よりも大きい、0 に等しい、 あるいは 0 よりも小さい整数を返す。比較は、
 *  ‘\200’ が ‘\0’ よりも大きくなるように、unsigned char を使って行う。
 */

int	ft_strcmp_len(char *s1, char *s2)
{
	if (ft_strlen(s1) != ft_strlen(s2))
		return (ft_strlen(s1) - ft_strlen(s2));
	while (*s1 != '\0' || *s2 != '\0')
	{
		if ((unsigned char)*s1 != (unsigned char)*s2)
			return ((unsigned char)*s1 - (unsigned char)*s2);
		s1++;
		s2++;
	}
	return (0);
}
